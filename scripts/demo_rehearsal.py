"""E-43: run the judge demo use case in ONE chat on AC20 through the API; writes results/demo_rehearsal.md.
Usage: python3 scripts/demo_rehearsal.py [base_url]   (default http://localhost:8000)"""
import json, sys, time, httpx
base = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8000"
DOC = "ifc_bench__ac20-arc"
TURNS = ["How many doors and windows are on the ground floor?", "And on the first floor?", "Where are the toilets?",
         "Remove the front door. Is it still compliant?", "Reset the model",
         "prep me for a client meeting about removing the main entrance"]
cid = httpx.post(f"{base}/api/chats", json={"doc_ids": [DOC], "title": "demo rehearsal"}, timeout=30).json()["id"]
rows = []
for q in TURNS:
    t = time.time(); first = None; ans = None; ev = None
    with httpx.stream("POST", f"{base}/api/chats/{cid}/messages", json={"content": q, "doc_ids": [DOC]}, timeout=180) as r:
        for line in r.iter_lines():
            if line.startswith("event:"): ev = line[6:].strip()
            elif line.startswith("data:"):
                if ev == "delta" and first is None: first = time.time() - t
                if ev == "answer":
                    ans = json.loads(line[5:])
    tot = time.time() - t
    a = ans.get("answer_obj", ans) if isinstance(ans, dict) else {}
    rows.append(dict(q=q, text=(a.get("answer") or {}).get("text_md", "(no answer)"), route=a.get("route"),
                     cost=(a.get("cost") or {}).get("usd_total"), first=first, total=tot,
                     boxes=len((a.get("evidence") or {}).get("boxes", [])), cites=len(a.get("citations", [])),
                     abst=(a.get("answer") or {}).get("abstained")))
    print(f"{tot:5.1f}s boxes={rows[-1]['boxes']} {q}\n   {rows[-1]['text'][:200]!r}", flush=True)
out = ["# Demo rehearsal (E-43)", "", f"Chat on `{DOC}` via {base}, {time.strftime('%Y-%m-%d %H:%M')}. Generated by scripts/demo_rehearsal.py.", "",
       "| # | Question | Route | Cost | First text | Total | Boxes | Cites |", "|---|---|---|---|---|---|---|---|"]
for i, r in enumerate(rows, 1):
    out.append(f"| {i} | {r['q']} | {r['route']} | ${r['cost'] or 0:.4f} | {(r['first'] if r['first'] is not None else r['total']):.1f} s{'' if r['first'] is not None else ' (answer, not streamed)'} | {r['total']:.1f} s | {r['boxes']} | {r['cites']} |")
out.append("")
for i, r in enumerate(rows, 1):
    out += [f"## Turn {i}: {r['q']}", "", r["text"], ""]
open("results/demo_rehearsal.md", "w").write("\n".join(out))
